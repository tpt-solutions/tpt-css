//! The support table in `docs/SUPPORT.md` is generated from the property
//! registry and the shorthand table (DESIGN.md decision 42). This test rebuilds
//! it and fails when the checked-in file is stale, so CI keeps it current.
//! `TPT_UPDATE_GENERATED=1 cargo test --test integration support` rewrites it.

use std::path::Path;

use tpt_css::properties::{Grammar, PROPERTIES, SHORTHANDS};
use tpt_css::values::serialize::serialize_value;

/// The short name of a grammar, for the table. The match is exhaustive, so a new
/// grammar cannot be added without a name here.
fn grammar_name(grammar: Grammar) -> &'static str {
    match grammar {
        Grammar::TextDecorationLine => "text-decoration-line",
        Grammar::Length { .. } => "length",
        Grammar::Keywords(_) => "keywords",
        Grammar::Color => "color",
        Grammar::LengthPercentage { .. } => "length-percentage",
        Grammar::BorderWidth => "border-width",
        Grammar::LineHeight => "line-height",
        Grammar::FontWeight => "font-weight",
        Grammar::FontFamily => "font-family",
        Grammar::Content => "content",
        Grammar::Opacity => "opacity",
        Grammar::FontStretch => "font-stretch",
        Grammar::BorderRadius => "border-radius",
        Grammar::Integer { .. } => "integer",
        Grammar::Image => "image",
        Grammar::Counters { .. } => "counters",
        Grammar::PassThrough => "pass-through (text)",
        Grammar::TimeList { .. } => "time-list",
        Grammar::Shadow => "shadow-list",
        Grammar::Transform => "transform-list",
        Grammar::KeywordSet { .. } => "keyword-set",
        Grammar::Alternates => "font-variant-alternates",
        Grammar::Number { .. } => "number",
        Grammar::TransitionProperty => "transition-property-list",
        Grammar::TimingFunctionList => "easing-list",
        Grammar::KeywordList { .. } => "keyword-list",
        Grammar::IterationCountList => "iteration-count-list",
        Grammar::AnimationName => "animation-name-list",
        Grammar::Filter => "filter-list",
        Grammar::BackgroundLayers { .. } => "background-layer-list",
    }
}

/// The generated Markdown.
fn generate() -> String {
    let mut out = String::new();
    out.push_str(
        "<!-- Generated by tests/integration/support.rs (DESIGN.md decision 42). \
         Do not edit by hand: run TPT_UPDATE_GENERATED=1 cargo test --test integration support -->\n\n",
    );
    out.push_str("# Property support\n\n");
    out.push_str(&format!(
        "{} properties are registered. A registered property is parsed and computed. \
         Pass-through properties keep their value as text. Properties that are not \
         registered are reported as `info` diagnostics and ignored.\n\n",
        PROPERTIES.len()
    ));
    out.push_str("| Property | Grammar | Inherited | Initial | Spec |\n");
    out.push_str("| --- | --- | --- | --- | --- |\n");
    for spec in PROPERTIES {
        out.push_str(&format!(
            "| `{}` | {} | {} | `{}` | [link]({}) |\n",
            spec.name,
            grammar_name(spec.grammar),
            if spec.inherited { "yes" } else { "no" },
            serialize_value(&spec.initial.to_value()),
            spec.spec_url,
        ));
    }
    out.push_str("\n## Shorthands\n\n");
    out.push_str(&format!(
        "{} shorthands expand into longhands. Their names: {}.\n",
        SHORTHANDS.len(),
        SHORTHANDS
            .iter()
            .map(|s| format!("`{}`", s.name))
            .collect::<Vec<_>>()
            .join(", ")
    ));
    out
}

#[test]
fn support_table_is_current() {
    let path = Path::new(env!("CARGO_MANIFEST_DIR")).join("docs/SUPPORT.md");
    let generated = generate();
    if std::env::var_os("TPT_UPDATE_GENERATED").is_some() {
        std::fs::write(&path, &generated).expect("docs/SUPPORT.md is writable");
        return;
    }
    // Checkouts on Windows may use CRLF; compare the text without it.
    let checked_in = std::fs::read_to_string(&path)
        .unwrap_or_default()
        .replace("\r\n", "\n");
    assert!(
        checked_in == generated,
        "docs/SUPPORT.md is out of date. Run `TPT_UPDATE_GENERATED=1 cargo test --test integration support`."
    );
}
